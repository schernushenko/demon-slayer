export function personArtwork(name: string): string {
  return personArtworkNames.has(name)
    ? `/persons/${encodeURIComponent(name)}.webp`
    : '/demon-slayer.jpg'
}

function character(
  id: number,
  name: string,
  age: number | null,
  gender: string,
  race: string,
  description: string,
  imagePosition: string,
): Character {
  return {
    id,
    name,
    age,
    gender,
    race,
    description,
    img: personArtwork(name),
    imagePosition,
    affiliation_id: 1,
    arc_id: 1,
    quote: null,
  }
}

